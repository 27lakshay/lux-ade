// The pre-paint CSS is a projection of the daemon's literal bundled colors.
import { readFileSync, writeFileSync } from 'node:fs'
import assert from 'node:assert/strict'

const source = new URL('../crates/ade-core/src/appearance/builtin.json', import.meta.url)
const target = new URL('../apps/desktop/src/renderer/src/appearance-defaults.css', import.meta.url)
const palettes = JSON.parse(readFileSync(source, 'utf8'))
const handoff = readFileSync(new URL('../docs/theme-palette-handoff.md', import.meta.url), 'utf8')
const approved = Object.fromEntries(
  [...handoff.matchAll(/^### (\w+) — (?:dark|light)\n[\s\S]*?```css\n([\s\S]*?)```/gm)].map(([, name, block]) => [
    name.toLowerCase(),
    Object.fromEntries(
      [...block.matchAll(/--([a-z0-9-]+):\s*(#[\da-fA-F]{6}(?:[\da-fA-F]{2})?);/g)].map(([, role, value]) => [
        role,
        value,
      ]),
    ),
  ]),
)
assert.equal(Object.keys(approved).length, 12, 'incomplete approved palette handoff')
assert.deepEqual(
  Object.keys(palettes).sort(),
  Object.keys(approved).sort(),
  'missing approved palette handoff variants',
)
for (const [name, tokens] of Object.entries(palettes)) {
  assert.equal(Object.keys(approved[name] ?? {}).length, 73, `${name}: incomplete approved palette handoff`)
  assert.deepEqual(tokens, approved[name], `${name}: colors or roles differ from the approved palette handoff`)
}

let css = '/* Generated by scripts/generate-theme-css.mjs from the shared ADE palettes. */\n'
for (const [selector, name] of [
  [':root', 'chalk'],
  ['.dark', 'graphite'],
]) {
  css += `${selector} {\n`
  for (const [role, value] of Object.entries(palettes[name])) css += `  --${role}: ${value.toLowerCase()};\n`
  css += '}\n'
}
const rolesTarget = new URL('../apps/desktop/src/shared/app-theme-roles.ts', import.meta.url)
const roles =
  '// Generated by scripts/generate-theme-css.mjs from the shared ADE palettes.\n' +
  'export const APP_THEME_ROLES = [\n' +
  Object.keys(palettes.graphite)
    .map((role) => `  '${role}',\n`)
    .join('') +
  '] as const\n'
for (const [file, contents] of [
  [target, css],
  [rolesTarget, roles],
]) {
  if (process.argv.includes('--check')) {
    if (readFileSync(file, 'utf8') !== contents) throw new Error('Run node scripts/generate-theme-css.mjs')
  } else writeFileSync(file, contents)
}
